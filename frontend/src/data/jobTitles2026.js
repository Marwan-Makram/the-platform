/**
 * Smart ranked search for 2026 job titles:
 * 1. Exact prefix matches on the full title (e.g. "it" -> "IT Support Specialist", "IT Helpdesk Technician")
 * 2. Word-boundary prefix matches (e.g. "help" -> "IT Helpdesk Technician")
 * 3. Substring matches (e.g. "design" -> "Product Designer")
 */
export function searchJobTitles2026(query, limit = 12) {
  const q = (query || '').trim().toLowerCase();
  if (!q) {
    return [];
  }

  const startsWithTitle = [];
  const wordStartsWith = [];
  const containsMatch = [];

  for (const item of JOB_TITLES_2026) {
    const lowerTitle = item.title.toLowerCase();
    const lowerCat = item.category.toLowerCase();
    const words = lowerTitle.split(/[\s/()-]+/);

    if (lowerTitle.startsWith(q)) {
      startsWithTitle.push(item);
    } else if (words.some((w) => w.startsWith(q))) {
      wordStartsWith.push(item);
    } else if (lowerTitle.includes(q) || lowerCat.includes(q)) {
      containsMatch.push(item);
    }
  }

  return [...startsWithTitle, ...wordStartsWith, ...containsMatch].slice(0, limit);
}
